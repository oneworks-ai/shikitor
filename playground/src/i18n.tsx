interface I18nContextValue {
  locale: Locale
  setLocale(locale: Locale): void
  t(key: string, variables?: Record<string, string | number>): string
}

const I18nContext = createContext<I18nContextValue | null>(null)

export function I18nProvider({ children }: { children: ReactNode }) {
  const { value: query, set } = useQueries<{ locale: Locale }>()
  const locale: Locale = query.locale === 'zh-CN' ? 'zh-CN' : 'en-US'
  useEffect(() => {
    document.documentElement.lang = locale
  }, [locale])
  const value = useMemo<I18nContextValue>(() => ({
    locale,
    setLocale: nextLocale => set('locale', nextLocale),
    t(key, variables = {}) {
      const message = messages[locale][key] ?? messages['en-US'][key] ?? key
      return message.replace(/\{(\w+)\}/g, (_, name: string) => String(variables[name] ?? `{${name}}`))
    }
  }), [locale, set])

  return (
    <I18nContext.Provider value={value}>
      <ConfigProvider globalConfig={locale === 'zh-CN' ? zhCN : enUS}>
        {children}
      </ConfigProvider>
    </I18nContext.Provider>
  )
}

export function useI18n() {
  const context = useContext(I18nContext)
  if (!context) throw new Error('useI18n must be used inside I18nProvider')
  return context
}
